#!/usr/bin/env python
"""Build, push, monitor and fetch self-contained Kaggle kernels for this project.

A pushed kernel is ONE python script = header (base64 tar.gz snapshot of the repo code + JSON params)
+ body from kaggle/kernels/<kind>.py. No code dataset to version, a push is atomic.

    python kaggle/launch.py whoami
    python kaggle/launch.py push cache --shards 3          # 3 CPU kernels: header scan + JPEG cache tar
    python kaggle/launch.py push extract                   # GPU kernel: vLLM + Qwen3 report extraction
    python kaggle/launch.py status                         # all kernels recorded in build/kernels/pushed.json
    python kaggle/launch.py pull extract --out labels/kaggle_extract
    python kaggle/launch.py run-local cache --comp-root /path/to/fake_comp --work /tmp/w   # dry run
"""
from __future__ import annotations

import argparse
import base64
import io
import json
import os
import re
import subprocess
import sys
import tarfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
BUILD = REPO / "build" / "kernels"
COMP = "rsna-knee-abnormality-detection"
KINDS = {
    "cache": {"body": "cache_shard.py", "gpu": False, "slug": "rsna-knee-cache-{i}of{n}"},
    "extract": {"body": "extract_reports.py", "gpu": True, "slug": "rsna-knee-extract"},
    "train": {"body": "train_fold.py", "gpu": True, "slug": "rsna-knee-train-{name}"},
    "infer": {"body": "infer_submit.py", "gpu": True, "internet": False, "slug": "rsna-knee-infer"},
    "patient": {"body": "scan_patient.py", "gpu": False, "slug": "rsna-knee-patient-meta"},
}
SNAPSHOT_GLOBS = ["rsna_knee/**/*.py", "scripts/*.py", "configs/*.yaml"]


def kaggle_bin() -> str:
    cand = Path(sys.executable).parent / "kaggle"
    return str(cand) if cand.exists() else "kaggle"


def run(cmd: list[str], check: bool = True, capture: bool = False) -> subprocess.CompletedProcess:
    print("$", " ".join(cmd), flush=True)
    return subprocess.run(cmd, check=check, text=True, capture_output=capture)


def username() -> str:
    if os.environ.get("KAGGLE_USERNAME"):
        return os.environ["KAGGLE_USERNAME"]
    legacy = Path.home() / ".kaggle" / "kaggle.json"
    if legacy.exists():
        return json.loads(legacy.read_text())["username"]
    out = subprocess.run([kaggle_bin(), "config", "view"], text=True, capture_output=True)
    m = re.search(r"username:\s*(\S+)", out.stdout + out.stderr)
    if not m or m.group(1) in ("None", ""):
        raise SystemExit("Kaggle auth missing: set KAGGLE_API_TOKEN, or create ~/.kaggle/access_token (chmod 600), "
                         "or ~/.kaggle/kaggle.json. Details: README, section 'Kaggle auth'.\n" + out.stdout[-400:])
    return m.group(1)


def snapshot(extra: list[str]) -> str:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        files = [p for g in SNAPSHOT_GLOBS for p in REPO.glob(g) if "__pycache__" not in p.parts]
        files += [Path(e).resolve() for e in extra]
        for p in sorted(set(files)):
            tar.add(p, arcname=str(p.relative_to(REPO)))
    return base64.b64encode(buf.getvalue()).decode()


HEADER = '''# AUTO-GENERATED by kaggle/launch.py - do not edit. Kind: {kind}
import base64, io, json, os, sys, tarfile
_CODE = os.environ.get("RSNA_CODE_DIR", "/tmp/rsna_code")
os.makedirs(_CODE, exist_ok=True)
tarfile.open(fileobj=io.BytesIO(base64.b64decode("{payload}")), mode="r:gz").extractall(_CODE)
sys.path.insert(0, _CODE)
os.environ["PYTHONPATH"] = _CODE + os.pathsep + os.environ.get("PYTHONPATH", "")  # worker processes too
KERNEL_PARAMS = json.loads({params!r})
KERNEL_PARAMS.update(json.loads(os.environ.get("RSNA_KERNEL_PARAMS", "{{}}")))
'''


def parse_params(items: list[str]) -> dict:
    out = {}
    for it in items or []:
        k, v = it.split("=", 1)
        try:
            out[k] = json.loads(v)
        except json.JSONDecodeError:
            out[k] = v
    return out


def build(kind: str, slug: str, params: dict, kernel_sources: list[str], embed: list[str], user: str | None,
          dataset_sources: list[str] | None = None) -> Path:
    spec = KINDS[kind]
    body = (REPO / "kaggle" / "kernels" / spec["body"]).read_text()
    script = HEADER.format(kind=kind, payload=snapshot(embed), params=json.dumps(params)) + "\n" + body
    out = BUILD / slug
    out.mkdir(parents=True, exist_ok=True)
    (out / "script.py").write_text(script)
    meta = {"id": f"{user or 'USER'}/{slug}", "title": slug, "code_file": "script.py", "language": "python",
            "kernel_type": "script", "is_private": "true", "enable_gpu": "true" if spec["gpu"] else "false",
            "enable_tpu": "false", "enable_internet": "true" if spec.get("internet", True) else "false", "machine_shape": "NvidiaTeslaT4" if spec["gpu"] else "",
            "dataset_sources": dataset_sources or [], "competition_sources": [COMP], "kernel_sources": kernel_sources, "model_sources": []}
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    print(f"built {out} ({len(script) / 1024:.0f} KB)")
    return out


def slugs_for(kind: str, a: argparse.Namespace) -> list[tuple[str, dict]]:
    params = parse_params(a.param)
    if kind == "cache":
        n = a.shards
        only = [int(x) for x in a.only.split(",")] if a.only else range(n)
        # --name gives a SEPARATE set of kernels: re-pushing the old slugs would replace the outputs other kernels mount
        fmt = KINDS[kind]["slug"] if a.name == "exp" else f"rsna-knee-cache-{a.name}-{{i}}of{{n}}"
        return [(fmt.format(i=i, n=n), {**params, "shard": f"{i}/{n}"}) for i in only]
    if kind == "train":
        return [(KINDS[kind]["slug"].format(name=a.name), {"run_name": a.name, **params})]
    if kind == "infer" and a.name != "exp":  # one kernel per model so that several can run / be submitted side by side
        return [(f"{KINDS[kind]['slug']}-{a.name}", params)]
    return [(KINDS[kind]["slug"], params)]


def record(slug: str, user: str, kind: str) -> None:
    p = BUILD / "pushed.json"
    d = json.loads(p.read_text()) if p.exists() else {}
    d[slug] = {"ref": f"{user}/{slug}", "kind": kind}
    p.write_text(json.dumps(d, indent=2))


def pushed(kind: str | None = None) -> dict:
    p = BUILD / "pushed.json"
    d = json.loads(p.read_text()) if p.exists() else {}
    return {k: v for k, v in d.items() if kind is None or v["kind"] == kind}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("whoami")
    for name in ("build", "push", "run-local"):
        sp = sub.add_parser(name)
        sp.add_argument("kind", choices=list(KINDS))
        sp.add_argument("--shards", type=int, default=3)
        sp.add_argument("--only", default="", help="cache: comma list of shard indices")
        sp.add_argument("--name", default="exp", help="train: run name")
        sp.add_argument("--param", action="append", default=[], help="k=v (JSON value) forwarded to the kernel")
        sp.add_argument("--kernel-source", action="append", default=[], help="user/slug whose output is mounted")
        sp.add_argument("--embed", action="append", default=[], help="extra repo file to ship inside the snapshot")
        sp.add_argument("--dataset-source", action="append", default=[], help="user/dataset mounted into the kernel")
        sp.add_argument("--comp-root", default="")
        sp.add_argument("--work", default="")
    sp = sub.add_parser("status"); sp.add_argument("kind", nargs="?", default=None)
    sp = sub.add_parser("pull"); sp.add_argument("kind"); sp.add_argument("--out", required=True)
    sp.add_argument("--pattern", default="", help="regex of files to download (skip multi-GB tars: e.g. '\\.(parquet|json|jsonl|csv|log)$')")
    a = ap.parse_args()

    if a.cmd == "whoami":
        print(username())
    elif a.cmd in ("build", "push", "run-local"):
        user = username() if a.cmd == "push" else None
        for slug, params in slugs_for(a.kind, a):
            out = build(a.kind, slug, params, a.kernel_source, a.embed, user, a.dataset_source)
            if a.cmd == "push":
                run([kaggle_bin(), "kernels", "push", "-p", str(out)])
                record(slug, user, a.kind)
            elif a.cmd == "run-local":
                env = {**os.environ, "RSNA_CODE_DIR": str(out / "_code")}
                if a.comp_root:
                    env["RSNA_COMP_ROOT"] = a.comp_root
                if a.work:
                    env["RSNA_WORK_DIR"] = a.work
                    env.setdefault("RSNA_TMP_DIR", os.path.join(a.work, "_tmp"))
                subprocess.run([sys.executable, str(out / "script.py")], check=True, env=env)
    elif a.cmd == "status":
        for slug, v in pushed(a.kind).items():
            r = run([kaggle_bin(), "kernels", "status", v["ref"]], check=False, capture=True)
            print(f"{slug}: {(r.stdout or r.stderr).strip().splitlines()[-1] if (r.stdout or r.stderr).strip() else '?'}")
    elif a.cmd == "pull":
        for slug, v in pushed(a.kind).items():
            cmd = [kaggle_bin(), "kernels", "output", v["ref"], "-p", os.path.join(a.out, slug)]
            if a.pattern:
                cmd += ["--file-pattern", a.pattern]
            run(cmd, check=False)


if __name__ == "__main__":
    main()
